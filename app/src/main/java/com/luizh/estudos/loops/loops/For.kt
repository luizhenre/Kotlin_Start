package com.luizh.estudos.loops.loops

/*
Tema: Relatório numérico

Enunciado:
Crie um programa que imprima todos os números de 1 até 50.
Ao final, mostre a mensagem:

Relatório finalizado


📌 Use for com intervalo (..)*/

fun main() {
    for (relatorio in 1..50) {
        println(relatorio)
    }
    println("Relatório finalizado")
}